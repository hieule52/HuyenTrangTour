export const popularRoutes = routes.filter((r) => r.popular);

export const getRoutesByCategory = (category: Route['category']) =>
  routes.filter((r) => r.category === category);

export const getRouteById = (id: string) =>
  routes.find((r) => r.id === id);

// Helper hàm lấy danh sách tuyến xe hiển thị đúng theo ngôn ngữ
export function getLocalizedRoutes(locale: string = 'vi'): Route[] {
  return routes.map((r) => ({
    ...r,
    name: r.nameI18n?.[locale] || r.name,
    description: r.descriptionI18n?.[locale] || r.description,
  }));
}
